#!/usr/bin/env python3
"""Generates src/UnicodeTables.cpp: the code point ranges of \\p{L} (letters)
and \\p{N} (numbers) used by the regex-style pre-tokenizers (GPT-2, Llama 3).

    python3 scripts/gen_unicode_tables.py > src/UnicodeTables.cpp
"""
import sys
import unicodedata


def ranges(prefix):
    out, start, prev = [], None, None
    for cp in range(0x110000):
        hit = unicodedata.category(chr(cp)).startswith(prefix)
        if hit and start is None:
            start = cp
        if not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def table(name, rs):
    lines = [f"const Range {name}[] = {{"]
    row = []
    for a, b in rs:
        row.append(f"{{0x{a:X}, 0x{b:X}}},")
        if len(row) == 6:
            lines.append("    " + " ".join(row))
            row = []
    if row:
        lines.append("    " + " ".join(row))
    lines.append("};")
    return "\n".join(lines)


def main():
    letters, numbers = ranges("L"), ranges("N")
    print(f"""// Generated by scripts/gen_unicode_tables.py from Unicode {unicodedata.unidata_version}; do not edit.
// {len(letters)} letter ranges (\\p{{L}}), {len(numbers)} number ranges (\\p{{N}}).
#include "UnicodeTables.h"

#include <algorithm>
#include <iterator>

namespace nc {{
namespace {{
struct Range {{
    std::uint32_t lo, hi;
}};

{table("kLetters", letters)}

{table("kNumbers", numbers)}

template <std::size_t N>
bool inRanges(const Range (&r)[N], std::uint32_t c) {{
    const Range* it = std::upper_bound(std::begin(r), std::end(r), c, [](std::uint32_t v, const Range& x) {{ return v < x.lo; }});
    return it != std::begin(r) && c <= (it - 1)->hi;
}}
}} // namespace

bool unicodeIsLetter(std::uint32_t c) {{ return inRanges(kLetters, c); }}
bool unicodeIsNumber(std::uint32_t c) {{ return inRanges(kNumbers, c); }}

}} // namespace nc""")


if __name__ == "__main__":
    sys.exit(main())
